#!/usr/bin/env python3
"""Generate structural-slice tasks for a Go repo from harness/gokeys (compiler-checked call graph).

Usage: make_structural_tasks_go.py <go repo checkout> <graph.json from gokeys> <out.yaml> [--label Gitea]
Eligible target: plain function (no receiver, not generic), never used as a function value (so not a
registered handler), not called from a package-level initialiser, unique bare name, 3-9 distinct callers,
and a textual cross-check agrees: the number of `name(` call-looking occurrences in non-test .go files
(excluding the definition) equals the number of call sites the type checker found. Depth-2 tasks need every
direct caller to be eligible in the same sense, so the second hop is exact too. Seeded shuffle, seed 27.
"""
import json, random, re, sys
from collections import Counter
from pathlib import Path
import yaml

SEED, N_DIRECT, N_DEPTH2, MIN_C, MAX_C = 27, 6, 6, 3, 9

def main():
    root, graph, out = Path(sys.argv[1]), json.load(open(sys.argv[2])), Path(sys.argv[3])
    label = sys.argv[sys.argv.index("--label") + 1] if "--label" in sys.argv else root.name
    by = {f["key"]: f for f in graph}
    bare = Counter(f["name"].split(".")[-1] for f in graph)
    text = "\n".join(p.read_text(encoding="utf-8", errors="ignore") for p in sorted(root.rglob("*.go"))
                     if not p.name.endswith("_test.go") and ".git/" not in p.as_posix())
    for f in graph: f["callers"] = f["callers"] or []
    def clean(f):
        return (not f["is_method"] and not f["generic"] and f["value_refs"] == 0 and not f["init_called"]
                and bare[f["name"]] == 1 and len(f["name"]) >= 8)
    occ = Counter(re.findall(r"\b(\w+)\s*\(", text))
    occ.subtract(Counter(re.findall(r"\bfunc\s+(\w+)\s*\(", text)))
    def textual_ok(f):
        return occ[f["name"]] == f["call_sites"]
    cand = []
    for f in graph:
        if not clean(f) or not (MIN_C <= len(f["callers"]) <= MAX_C) or not textual_ok(f): continue
        cs = [by[c] for c in f["callers"] if c in by]
        if len(cs) != len(f["callers"]): continue
        cand.append((f, cs))
    rng = random.Random(SEED); rng.shuffle(cand)
    direct = cand[:N_DIRECT]; used = {c[0]["key"] for c in direct}
    depth2 = []
    for f, cs in cand[N_DIRECT:]:
        if f["key"] in used: continue
        if not all(clean(c) and textual_ok(c) for c in cs): continue
        d1 = {c["key"] for c in cs}
        d2 = sorted({k for c in cs for k in c["callers"]} - d1 - {f["key"]})
        if 2 <= len(d2) <= 12 and all(k in by for k in d2): depth2.append((f, cs, [by[k] for k in d2]))
        if len(depth2) == N_DEPTH2: break
    split = lambda k: k.split("::", 1)
    tasks = []
    def fact(k, what): p, q = split(k); return f"`{q}` in {p} {what}"
    G = f"Structural slice: callers / impact (compiler-keyed, {label})"
    for i, (f, cs) in enumerate(direct, 1):
        tasks.append({"id": f"S{i:02d}", "group": "S", "group_title": G, "origin_note": f"direct callers of {f['name']}",
            "question": (f"In the {label} codebase (Go, excluding tests), the function `{f['name']}` is defined in {f['file']}. "
                         f"List every function or method that calls `{f['name']}` directly (file path and function name for each). "
                         f"Be complete: if `{f['name']}` changes its signature, these are the places that must be updated."),
            "key_facts": [fact(c["key"], f"calls `{f['name']}`.") for c in cs],
            "anchor_files": sorted({f["file"], *[c["file"] for c in cs]})})
    for j, (f, cs, d2) in enumerate(depth2, N_DIRECT + 1):
        tasks.append({"id": f"S{j:02d}", "group": "S", "group_title": G, "origin_note": f"callers and callers-of-callers of {f['name']}",
            "question": (f"In the {label} codebase (Go, excluding tests), the function `{f['name']}` is defined in {f['file']}. "
                         f"If its behaviour changes, which functions are affected? List (1) every function that calls `{f['name']}` "
                         f"directly and (2) every function that calls one of those direct callers (two hops out). "
                         f"Give file path and function name for each."),
            "key_facts": [fact(c["key"], f"calls `{f['name']}` directly.") for c in cs]
                         + [fact(c["key"], f"is a second-hop caller (calls a direct caller of `{f['name']}`).") for c in d2],
            "anchor_files": sorted({f["file"], *[c["file"] for c in cs], *[c["file"] for c in d2]})})
    out.write_text(f"# GENERATED by harness/make_structural_tasks_go.py (seed {SEED}) from harness/gokeys; do not hand-edit.\n"
                   + yaml.safe_dump({"tasks": tasks}, sort_keys=False, width=120, allow_unicode=True), encoding="utf-8")
    print(f"{len(cand)} eligible targets; wrote {len(tasks)} tasks ({len(direct)} direct, {len(depth2)} depth-2)")

if __name__ == "__main__": main()
